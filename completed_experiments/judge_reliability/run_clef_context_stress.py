#!/usr/bin/env python3
"""Phase C (context panel) for Clef: near-context-limit stress test.

Reconstruction of the #122 context-stress design: cases judge-001/003/005,
neutral filler (62,000 chars by default) placed before or after the ground
truth inside the ground-truth field, candidate answer and expected label
fixed, plus a no-filler baseline. #122 does not include its filler text, so the
filler here is generated by this script; results are comparable in design but
not in exact prompt content. Also probes that the truncation guard fires on an
input over max_length.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
import time
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent
if str(HERE) not in sys.path:
    sys.path.insert(0, str(HERE))

import run_clef_preflight as clef

SUITE_VERSION = "context-stress-1-clef-reconstruction"
CASE_IDS = ("judge-001", "judge-003", "judge-005")
CONDITIONS = ("baseline", "ground_truth_early", "ground_truth_late")

FILLER_SENTENCES = (
    "The community library opens at nine in the morning and closes at six in the evening on weekdays.",
    "To make a simple tomato sauce, simmer chopped tomatoes with olive oil, garlic, and a pinch of salt for twenty minutes.",
    "A triangle with sides of three, four, and five units contains a right angle.",
    "The municipal bus route runs every fifteen minutes between the train station and the university campus.",
    "Granite is an igneous rock composed mainly of quartz and feldspar crystals.",
    "Regular stretching before a long walk can help reduce stiffness in the legs.",
    "The annual town fair features a pie-baking contest, a pottery stall, and a small brass band.",
    "In chess, each player begins with sixteen pieces, including eight pawns and a king.",
    "A well-organized spreadsheet uses one row per record and one column per attribute.",
    "Sourdough bread relies on a fermented starter made from flour and water instead of commercial yeast.",
    "The museum's east wing displays a collection of nineteenth-century clocks and pocket watches.",
    "Rainwater collected in a barrel can be used to water garden beds during dry weeks.",
    "The recipe calls for two cups of flour, one teaspoon of baking powder, and a half cup of milk.",
    "Printing a document double-sided saves paper and reduces the weight of a mailed package.",
    "A standard guitar has six strings tuned to E, A, D, G, B, and E.",
    "The ferry crosses the harbor in about twenty-five minutes when the water is calm.",
    "Tomato plants grow best with at least six hours of direct sunlight each day.",
    "The committee agreed to meet on the second Tuesday of each month at seven o'clock.",
    "A metric ton is equal to one thousand kilograms.",
    "The painter mixed blue and yellow pigments to produce a soft shade of green.",
)


def build_filler(chars: int) -> str:
    parts: list[str] = []
    total = 0
    i = 0

    while total < chars:
        sentence = FILLER_SENTENCES[i % len(FILLER_SENTENCES)]
        part = f"Background note {i + 1}: {sentence}"
        parts.append(part)
        total += len(part) + 1
        i += 1

    return "\n".join(parts)[:chars]


def with_context(item: dict[str, Any], condition: str, filler: str) -> dict[str, Any]:
    if condition == "baseline":
        return item

    truth = item["ground_truth_answer"]
    combined = (
        f"{filler}\n\n{truth}"
        if condition == "ground_truth_early"
        else f"{truth}\n\n{filler}"
    )

    return {**item, "ground_truth_answer": combined}


def load_cases(repo: Path) -> dict[str, dict[str, Any]]:
    path = repo / "eval" / "judge_cases.jsonl"
    selected: dict[str, dict[str, Any]] = {}

    for raw in path.read_text(encoding="utf-8").splitlines():
        if raw.strip():
            row = json.loads(raw)
            if row.get("case_id") in CASE_IDS:
                selected[row["case_id"]] = row

    missing = [c for c in CASE_IDS if c not in selected]
    if missing:
        raise ValueError(f"Missing context-stress cases: {missing}")

    return selected


def build_tasks(
    cases: dict[str, dict[str, Any]],
    filler_chars: int,
) -> list[dict[str, Any]]:
    filler = build_filler(filler_chars)
    tasks = []

    for condition in CONDITIONS:
        for cid in CASE_IDS:
            case = cases[cid]
            tasks.append({
                "task_id": f"context::{condition}::{cid}",
                "condition": condition,
                "source_case_id": cid,
                "expected_label": case["expected_label"],
                "item": with_context(case["item"], condition, filler),
                "candidate_answer": case["model_answer"],
            })

    return tasks


def accuracy_block(rows: list[dict[str, Any]]) -> dict[str, Any]:
    total = len(rows)
    correct = sum(r["correct"] for r in rows)
    tokens = [r["input_tokens"] for r in rows if r.get("input_tokens")]

    return {
        "total": total,
        "correct": correct,
        "accuracy": correct / total if total else None,
        "invalid_count": sum(r["status"] != "ok" for r in rows),
        "input_tokens_min": min(tokens) if tokens else None,
        "input_tokens_max": max(tokens) if tokens else None,
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", required=True)
    ap.add_argument("--output-dir", required=True)
    ap.add_argument("--model-id", default=clef.DEFAULT_MODEL_ID)
    ap.add_argument("--revision", default=clef.DEFAULT_MODEL_REVISION)
    ap.add_argument("--device", default="cuda")
    ap.add_argument(
        "--dtype",
        choices=("bfloat16", "float16", "float32"),
        default="bfloat16",
    )
    ap.add_argument("--max-length", type=int, default=16384)
    ap.add_argument("--filler-chars", type=int, default=62000)

    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--inspect-only", action="store_true")
    mode.add_argument("--run", action="store_true")

    args = ap.parse_args()

    repo = Path(args.repo).expanduser().resolve()
    out_dir = Path(args.output_dir).expanduser().resolve()
    out_dir.mkdir(parents=True, exist_ok=True)

    cases = load_cases(repo)
    tasks = build_tasks(cases, args.filler_chars)

    plan = {
        "suite_version": SUITE_VERSION,
        "case_ids": list(CASE_IDS),
        "conditions": list(CONDITIONS),
        "filler_chars": args.filler_chars,
        "filler_sha256": hashlib.sha256(
            build_filler(args.filler_chars).encode("utf-8")
        ).hexdigest(),
        "call_count": len(tasks),
        "max_length": args.max_length,
        "model_id": args.model_id,
        "requested_revision": args.revision,
        "case_file_sha256": clef.file_sha256(repo / "eval" / "judge_cases.jsonl"),
        "note": (
            "Reconstruction of the #122 context-stress design; #122's filler "
            "text is not in the repository."
        ),
    }

    clef.write_json(out_dir / "context_preflight.json", plan)

    if args.inspect_only:
        print(json.dumps(plan, indent=2))
        print("Inspection complete. No model was downloaded or called.")
        return 0

    try:
        import torch
        from huggingface_hub import HfApi, snapshot_download

        resolved_revision = HfApi().model_info(
            args.model_id, revision=args.revision
        ).sha

        model_path = snapshot_download(
            repo_id=args.model_id, revision=resolved_revision
        )

        if model_path not in sys.path:
            sys.path.insert(0, model_path)

        from joint_schema_model import (
            encode_record,
            load_release_model,
            systemone,
        )

        model, processor = load_release_model(
            model_path,
            device=args.device,
            dtype={
                "bfloat16": torch.bfloat16,
                "float16": torch.float16,
                "float32": torch.float32,
            }[args.dtype],
        )
    except Exception as exc:
        failure = {
            "stage": "model_setup",
            "error_type": type(exc).__name__,
            "error": str(exc),
        }
        clef.write_json(out_dir / "context_failure.json", failure)
        print(json.dumps(failure, indent=2))
        return 2

    rows: list[dict[str, Any]] = []

    for index, task in enumerate(tasks, 1):
        request = clef.build_clef_request(task, args.model_id)

        try:
            input_tokens = clef.check_no_truncation(
                encode_record, processor, request, args.max_length
            )

            started = time.perf_counter()
            response = systemone(
                model, processor, request, max_length=args.max_length
            )
            elapsed = time.perf_counter() - started

            choice, confidence, probabilities = clef.parse_clef_response(response)

            row = {
                **{k: v for k, v in task.items() if k != "item"},
                "status": "ok",
                "choice": choice,
                "confidence": confidence,
                "probabilities": probabilities,
                "correct": choice == task["expected_label"],
                "input_tokens": input_tokens,
                "ground_truth_chars": len(task["item"]["ground_truth_answer"]),
                "elapsed_seconds": elapsed,
                "retry_count": 0,
                "raw_response": response,
            }
        except Exception as exc:
            row = {
                **{k: v for k, v in task.items() if k != "item"},
                "status": "error",
                "choice": None,
                "correct": False,
                "input_tokens": None,
                "error_type": type(exc).__name__,
                "error": str(exc),
                "retry_count": 0,
            }

        rows.append(row)
        clef.write_jsonl(out_dir / "context_results.jsonl", rows)

        print(
            f"[{index}/{len(tasks)}] {task['task_id']}: "
            f"expected={task['expected_label']} choice={row['choice']} "
            f"tokens={row.get('input_tokens')} status={row['status']}"
            + (f" error={row['error']}" if row["status"] != "ok" else ""),
            flush=True,
        )

    # Guard probe: an input over max_length must raise, not be truncated.
    probe_task = build_tasks(cases, args.filler_chars * 2)[CONDITIONS.index("ground_truth_late") * len(CASE_IDS)]
    probe_request = clef.build_clef_request(probe_task, args.model_id)

    try:
        tokens = clef.check_no_truncation(
            encode_record, processor, probe_request, args.max_length
        )
        probe = {"guard_raised": False, "input_tokens": tokens}
    except ValueError as exc:
        probe = {"guard_raised": True, "message": str(exc)}

    probe.update({"filler_chars": args.filler_chars * 2, "max_length": args.max_length})
    clef.write_json(out_dir / "guard_probe.json", probe)

    summary = {
        "suite_version": SUITE_VERSION,
        "model": f"{args.model_id}@{resolved_revision}",
        "total_calls": len(rows),
        "conditions": {
            c: accuracy_block([r for r in rows if r["condition"] == c])
            for c in CONDITIONS
        },
        "paired_cases": [
            {
                "source_case_id": cid,
                "expected_label": cases[cid]["expected_label"],
                **{
                    c: next(
                        r["choice"]
                        for r in rows
                        if r["condition"] == c and r["source_case_id"] == cid
                    )
                    for c in CONDITIONS
                },
            }
            for cid in CASE_IDS
        ],
        "guard_probe": probe,
    }

    clef.write_json(out_dir / "context_summary.json", summary)
    clef.write_json(
        out_dir / "context_manifest.json",
        {
            **plan,
            "resolved_revision": resolved_revision,
            "suite_commit": clef.git_head(repo),
            "runner_file_sha256": clef.file_sha256(Path(__file__)),
            "adapter_file_sha256": clef.file_sha256(HERE / "run_clef_preflight.py"),
            "runtime": clef.runtime_metadata(torch, args.device, args.dtype),
            "inference_retries": 0,
        },
    )

    print(json.dumps(summary, indent=2))
    return 0 if all(r["status"] == "ok" for r in rows) else 2


if __name__ == "__main__":
    raise SystemExit(main())
